import fs from "node:fs/promises";
import path from "node:path";

const originalFetch = globalThis.fetch;
const manifestPath = path.resolve("src/content/blog/zebrabyte-generated/_manifest.json");
const slugModulePath = path.resolve("worker/blog-zebrabyte-slugs.ts");

if (typeof originalFetch !== "function") {
  throw new Error("Global fetch is required for the ZebraByte blog sync.");
}

function optimizedSanityImageRequest(input) {
  const rawUrl =
    input instanceof Request
      ? input.url
      : input instanceof URL
        ? input.toString()
        : typeof input === "string"
          ? input
          : null;

  if (!rawUrl) return input;

  let url;
  try {
    url = new URL(rawUrl);
  } catch {
    return input;
  }

  if (url.hostname !== "cdn.sanity.io" || !url.pathname.includes("/images/")) {
    return input;
  }

  // Ask Sanity's image pipeline to resize and encode before the asset enters
  // the repo/build output. The public article column is at most 720px wide, so
  // 1600px retains enough density for high-DPI screens without multi-MB originals.
  url.searchParams.set("w", "1600");
  url.searchParams.set("fit", "max");
  url.searchParams.set("q", "82");
  url.searchParams.set("fm", "webp");

  if (input instanceof Request) {
    return new Request(url.toString(), input);
  }
  return url.toString();
}

async function writeZebraByteSlugModule() {
  const manifest = JSON.parse(await fs.readFile(manifestPath, "utf8"));
  const slugs = [...new Set((manifest.imported ?? []).map((entry) => String(entry.slug || "").trim()).filter(Boolean))]
    .sort((a, b) => a.localeCompare(b));

  const source = [
    "// Generated by tools/sync-zebrabyte-blog-optimized.mjs. Do not edit manually.",
    `export const zebrabyteBlogSlugs: ReadonlySet<string> = new Set(${JSON.stringify(slugs, null, 2)});`,
    "",
  ].join("\n");

  await fs.writeFile(slugModulePath, source, "utf8");
  console.log(`[blog-sync] ${slugs.length} ZebraByte blog slug(s) enabled for direct Romanian streaming.`);
}

globalThis.fetch = (input, init) => originalFetch(optimizedSanityImageRequest(input), init);

try {
  await import("./sync-zebrabyte-blog-v2.mjs");
  await writeZebraByteSlugModule();
} finally {
  globalThis.fetch = originalFetch;
}
